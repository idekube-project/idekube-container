#!/bin/bash
#
# authn.sh — Render the nginx access-token authentication config.
#
# Runs on every start before nginx serves traffic: startup.sh in containers,
# idekube-authn.service in QEMU/WSL VMs. It always renders
# /etc/nginx/conf.d/access_token.conf from scratch:
#
#   IDEKUBE_ACCESS_TOKEN set and valid -> token map, from the read-only
#                                         template in /etc/idekube/nginx/
#   IDEKUBE_ACCESS_TOKEN unset         -> permit-all map
#   anything goes wrong                -> deny-all map, exit 1
#
# The template is never modified, so rotating the token (or setting one
# after running without) takes effect on the next run. Callers must treat a
# non-zero exit as fatal and not serve traffic.
#
set -euo pipefail

TEMPLATE=${IDEKUBE_AUTHN_TEMPLATE:-/etc/idekube/nginx/access_token.conf.template}
CONF=${IDEKUBE_AUTHN_CONF:-/etc/nginx/conf.d/access_token.conf}
PLACEHOLDER=__IDEKUBE_ACCESS_TOKEN_REGEX__

# Print a map that does not look at any token. $1: 1 = permit all, 0 = deny all.
static_map() {
    local permitted=$1
    echo "# Generated by authn.sh; do not edit."
    if [ "$permitted" = 1 ]; then
        echo "# IDEKUBE_ACCESS_TOKEN is not set: permit all requests."
    else
        echo "# Access-token setup failed: deny all token-protected requests."
    fi
    # The intermediate variables must still be defined because
    # sites-enabled/default references them (cookie-set rewrite, etc.).
    cat <<NGINX_EOF
map \$args \$__idekube_token_from_arg { default ""; }
map \$__idekube_token_from_arg \$__idekube_token_arg_ok { default 0; }
map \$cookie_idekube_container_access_token \$__idekube_token_cookie_ok { default 0; }
map \$http_x_idekube_container_access_token \$__idekube_token_header_ok { default 0; }
map \$request_uri \$idekube_access_permitted { default ${permitted}; }
NGINX_EOF
}

# Atomically replace $CONF with stdin.
install_conf() {
    local tmp
    tmp=$(mktemp "${CONF}.XXXXXX")
    cat > "$tmp"
    chmod 644 "$tmp"
    mv -f "$tmp" "$CONF"
}

fail() {
    echo "ERROR: $*" >&2
    echo "       Leaving nginx in deny-all mode." >&2
    static_map 0 | install_conf || echo "ERROR: could not write deny-all config to $CONF" >&2
    exit 1
}

if [ -n "${IDEKUBE_ACCESS_TOKEN:-}" ]; then
    # Unreserved URL characters only. The login form, query string, cookie
    # and header then all carry the token byte-for-byte (no percent-encoding
    # differences), and only "." needs escaping in the regex below.
    if [[ ! "$IDEKUBE_ACCESS_TOKEN" =~ ^[A-Za-z0-9._-]+$ ]]; then
        fail "IDEKUBE_ACCESS_TOKEN contains invalid characters." \
             "Only letters, digits, '.', '_' and '-' are allowed."
    fi
    [ -r "$TEMPLATE" ] || fail "access-token template $TEMPLATE is missing."

    echo "Configuring nginx access token authentication"
    token_regex=${IDEKUBE_ACCESS_TOKEN//./\\.}
    rendered=$(<"$TEMPLATE")
    rendered=${rendered//"$PLACEHOLDER"/"$token_regex"}
    if [[ "$rendered" == *__IDEKUBE_* ]] || [[ "$rendered" != *"$token_regex"* ]]; then
        fail "rendering $TEMPLATE did not produce a complete token map."
    fi
    printf '%s\n' "$rendered" | install_conf
else
    echo "IDEKUBE_ACCESS_TOKEN is not set, allowing all requests"
    static_map 1 | install_conf
fi

if command -v nginx >/dev/null 2>&1; then
    if ! nginx_out=$(nginx -t -q 2>&1); then
        echo "$nginx_out" >&2
        fail "nginx rejected the generated configuration."
    fi
fi
echo "Access token configuration written to $CONF"
